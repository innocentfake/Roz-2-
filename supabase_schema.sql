-- Run this in Supabase SQL Editor.
-- IMPORTANT: The app uses the Supabase service-role key server-side via Streamlit secrets.
-- Never expose that key in browser JavaScript or commit it to GitHub.
create extension if not exists pgcrypto;

create table if not exists public.roz_messages (
    id bigint generated by default as identity primary key,
    room_id text not null,
    sender text not null default 'Guest',
    kind text not null default 'Note',
    body text not null check (char_length(body) <= 1200),
    reply_to bigint references public.roz_messages(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists roz_messages_room_created_idx
on public.roz_messages (room_id, created_at desc);

create table if not exists public.roz_reactions (
    id bigint generated by default as identity primary key,
    message_id bigint not null references public.roz_messages(id) on delete cascade,
    room_id text not null,
    reactor text not null default 'Guest',
    reaction text not null,
    created_at timestamptz not null default now(),
    unique (message_id, reactor, reaction)
);

-- RLS is enabled. The Streamlit server uses the service-role key, which bypasses RLS.
-- Keep the service-role key ONLY in Streamlit Secrets / environment variables.
alter table public.roz_messages enable row level security;
alter table public.roz_reactions enable row level security;
-- No anon policies are created intentionally.
